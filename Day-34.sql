-- 🏢 Business Scenario
-- The marketing team wants to generate all possible customer-product combinations for a recommendation campaign and analyse the potential product choices.
-- Display
-- Customer Name, Customer City, Product Name, Brand, Price, Rating.
-- Tables
-- Customer
-- Inventory


-- Requirements
-- 1. Generate every possible customer-product combination using CROSS JOIN.
-- 2. Include customers from BENGALURU, MUMBAI, PUNE, or HYDERABAD.
-- 3. Exclude customers whose gender is Female.
-- 4. Product price must be between ₹2,000 and ₹60,000.
-- 5. Product rating must be at least 3.
-- 6. Product name must contain the letter a.
-- 7. Brand must not start with S.
-- 8. Exclude products with status DISCONTINUED or OUT OF STOCK.
-- 9. Use COUNT(*) to count the qualifying customer-product combinations.
-- 10. Sort by product price descending, then customer name ascending.



SELECT Customer.Customer_Name,
       Customer.City,
       Inventory.Product_Name,
       Inventory.Brand,
       Inventory.Price,
       Inventory.Rating,
       COUNT(*) OVER () AS Total_Combinations
FROM Customer
CROSS JOIN Inventory
WHERE Customer.City IN ('BENGALURU', 'MUMBAI', 'PUNE', 'HYDERABAD')
AND Customer.Gender NOT IN ('Female')
AND Inventory.Price BETWEEN 2000 AND 60000
AND Inventory.Rating >= 3
AND Inventory.Product_Name LIKE '%a%'
AND Inventory.Brand NOT LIKE 'S%'
AND Inventory.Product_Status NOT IN ('DISCONTINUED', 'OUT OF STOCK')
ORDER BY Inventory.Price DESC,
         Customer.Customer_Name ASC;



-- # MySQL Notes: COUNT(*) vs COUNT(*) OVER ()

-- ## 1. What is COUNT(*)?

-- `COUNT(*)` counts the number of rows in a result.

-- Example:

-- ```sql
-- SELECT COUNT(*) AS Total_Combinations
-- FROM Customer
-- CROSS JOIN Inventory;
-- ```

-- Explanation:
-- - `COUNT(*)` counts all rows generated by the CROSS JOIN.
-- - `AS Total_Combinations` gives the output column a meaningful name.
-- - This query returns only one row containing the total count.

-- ## 2. What is AS?

-- `AS` is used to give a temporary name (alias) to a column or table in a query result.

-- Example:

-- ```sql
-- SELECT COUNT(*) AS Total_Combinations
-- FROM Customer
-- CROSS JOIN Inventory;
-- ```

-- Here, `Total_Combinations` is the name displayed for the count column.

-- ## 3. What is OVER ()?

-- `OVER ()` turns an aggregate function into a window function.

-- It allows us to calculate a value across a set of rows while keeping the individual rows visible.

-- Example:

-- ```sql
-- SELECT Customer.Customer_Name,
--        Inventory.Product_Name,
--        COUNT(*) OVER () AS Total_Combinations
-- FROM Customer
-- CROSS JOIN Inventory;
-- ```

-- Explanation:
-- - Customer and product details remain visible.
-- - `COUNT(*) OVER ()` counts all rows in the query result.
-- - The total count is repeated in every row.
-- - Empty parentheses in `OVER ()` mean the entire result set is used as one window.

-- ## 4. Difference Between COUNT(*) and COUNT(*) OVER ()

-- ### COUNT(*) without OVER ()

-- ```sql
-- SELECT COUNT(*) AS Total_Combinations
-- FROM Customer
-- CROSS JOIN Inventory;
-- ```

-- Output example:

-- | Total_Combinations |
-- |---:|
-- | 100 |

-- It returns one row containing the total count.

-- ### COUNT(*) OVER ()

-- ```sql
-- SELECT Customer.Customer_Name,
--        Inventory.Product_Name,
--        COUNT(*) OVER () AS Total_Combinations
-- FROM Customer
-- CROSS JOIN Inventory;
-- ```

-- Output example:

-- | Customer_Name | Product_Name | Total_Combinations |
-- |---|---|---:|
-- | Rahul | Laptop | 100 |
-- | Rahul | Mouse | 100 |
-- | Priya | Laptop | 100 |
-- | Priya | Mouse | 100 |

-- It displays individual combinations and repeats the total count in every row.

-- *The numbers and names above are examples only.*

-- ## 5. COUNT(*) OVER () with WHERE

-- ```sql
-- SELECT Customer.Customer_Name,
--        Customer.City,
--        Inventory.Product_Name,
--        Inventory.Price,
--        COUNT(*) OVER () AS Total_Combinations
-- FROM Customer
-- CROSS JOIN Inventory
-- WHERE Customer.City IN ('BENGALURU', 'MUMBAI', 'PUNE', 'HYDERABAD')
-- AND Customer.Gender NOT IN ('Female')
-- AND Inventory.Price BETWEEN 2000 AND 60000
-- AND Inventory.Rating >= 3
-- AND Inventory.Product_Name LIKE '%a%'
-- AND Inventory.Brand NOT LIKE 'S%'
-- AND Inventory.Product_Status NOT IN ('DISCONTINUED', 'OUT OF STOCK')
-- ORDER BY Inventory.Price DESC,
--          Customer.Customer_Name ASC;
-- ```

-- Execution concept:
-- 1. CROSS JOIN generates all possible customer-product combinations.
-- 2. WHERE filters the combinations.
-- 3. COUNT(*) OVER () counts the rows remaining after filtering.
-- 4. ORDER BY sorts the result.

-- If 20 combinations remain after filtering, every row displays `Total_Combinations = 20`.

-- ## 6. COUNT(*) OVER (PARTITION BY ...)

-- `PARTITION BY` calculates a separate count for each group without combining the rows into one result per group.

-- Example:

-- ```sql
-- SELECT Customer.City,
--        Customer.Customer_Name,
--        COUNT(*) OVER (PARTITION BY Customer.City) AS City_Combinations
-- FROM Customer
-- CROSS JOIN Inventory;
-- ```

-- Explanation:
-- - `PARTITION BY Customer.City` divides the result into groups based on city.
-- - Each row displays the number of combinations for its city.
-- - Individual customer details remain visible.

-- ## 7. Quick Comparison

-- | Expression | Meaning |
-- |---|---|
-- | `COUNT(*)` | Counts rows in the result or current group |
-- | `COUNT(*) OVER ()` | Counts all rows in the window and keeps individual rows visible |
-- | `COUNT(*) OVER (PARTITION BY Customer.City)` | Counts rows separately for each city |

-- ## 8. Important Points

-- - `COUNT(*)` counts rows, including rows containing NULL values.
-- - `COUNT(column_name)` counts only rows where that column is not NULL.
-- - `COUNT(*)` without GROUP BY returns one row containing the total count.
-- - `COUNT(*) OVER ()` keeps the individual result rows visible.
-- - `PARTITION BY` calculates separate window results for each group.
-- - Window functions such as `COUNT(*) OVER ()` are supported in MySQL 8.0 and later.
